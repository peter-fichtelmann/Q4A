"""Build blacklist_external.txt from third-party profanity lists.

Sources (download them first, they are not vendored):
- better_profanity (MIT): better_profanity/profanity_wordlist.txt inside the wheel,
  `pip download --no-deps better_profanity` and unzip it.
- LDNOOBW "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" (CC BY 4.0):
  https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words,
  one file per language code.

Usage:
    python -m name_filter.build_external_blacklist <profanity_wordlist.txt> <LDNOOBW checkout dir>

Every source entry becomes a whole-word entry ("=") so it cannot block longer harmless
words; entries with spaces stay phrases, and Chinese/Japanese/Thai entries are matched
inside the name because those scripts have no spaces (single characters of those
scripts are dropped). Entries the hand-written
blacklist.txt already catches are skipped, and so are those in external_exclude.txt:
ordinary words that the sources list (mostly because they can be used sexually).
"""

from __future__ import annotations

import sys
from pathlib import Path

from name_filter.name_filter import _DATA_DIR, NameFilter, _is_unspaced_script, _normalise

OUTPUT = _DATA_DIR / "blacklist_external.txt"
EXCLUDE = _DATA_DIR / "external_exclude.txt"

HEADER = """\
# GENERATED by build_external_blacklist.py, do not edit by hand: add exclusions to
# external_exclude.txt and hand-picked entries to blacklist.txt instead.
#
# Derived from:
# - better_profanity word list, MIT License, https://github.com/snguyenthanh/better_profanity
# - "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" by LDNOOBW contributors,
#   CC BY 4.0, https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
#   (entries normalised, deduplicated and filtered for player names).
"""


def _key(entry: str) -> str:
    return " ".join(_normalise(entry).split())


def _read(path: Path) -> list:
    return [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main(better_profanity_list: str, ldnoobw_dir: str) -> None:
    sources = {"better_profanity": _read(Path(better_profanity_list))}
    for path in sorted(Path(ldnoobw_dir).iterdir()):
        if path.is_file() and path.suffix == "" and path.name not in ("LICENSE", "README", "USERS"):
            sources[f"LDNOOBW {path.name}"] = _read(path)

    curated = NameFilter(blacklist_paths=(_DATA_DIR / "blacklist.txt",))
    excluded = {_key(line) for line in NameFilter._read_lines(EXCLUDE)} if EXCLUDE.exists() else set()
    seen = set()
    sections = []
    for source, entries in sources.items():
        lines = []
        for entry in entries:
            key = _key(entry)
            if not key.replace(" ", "") or key in seen or key in excluded:
                continue
            seen.add(key)
            if curated.find_foul_word(entry) is not None:
                continue
            # a single Chinese/Japanese/Thai character (性, 奶) is part of countless everyday words
            if _is_unspaced_script(key) and len(key) == 1:
                continue
            whole = " " not in key and not _is_unspaced_script(key)
            lines.append(("=" if whole else "") + entry)
        if lines:
            sections.append(f"\n# --- {source} ---\n" + "\n".join(lines) + "\n")
    OUTPUT.write_text(HEADER + "".join(sections), encoding="utf-8", newline="\n")
    print(f"wrote {sum(s.count(chr(10)) - 2 for s in sections)} entries to {OUTPUT}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
